/// One scripted name search, and everything this fixture knows about it before
/// the session runs.
struct NameCase {
    /// What a reader of the published rows sees.
    label: &'static str,
    family: &'static str,
    /// Which of the two shapes the answer arm recognises this is.
    lever: &'static str,
    /// The call, spelled the way this family spells it.
    payload: String,
    /// The paths this member's index will match. The frame's total.
    matched: Vec<String>,
    /// Those of them an answer may name, which is what the pool may count.
    priced: Vec<String>,
    /// For a **glob**, whether the hundred the product prices is one this
    /// fixture knows — see [`claim_of`] and [`hundred_is_knowable`]. Ignored
    /// for a listing, whose price does not depend on a ranking at all.
    exact: bool,
    /// Whether Rift answers this shape at all.
    answerable: bool,
    /// Whether the bar's denominator counts it — see the ★ below.
    prescribed: bool,
}

/// How one scripted search is spelled, and what of the corpus it matches.
///
/// The pattern a call carries is the pattern this fixture has to match itself,
/// so a script line names its shape once and the payload, the family, the
/// lever and the match set are all read off it. Spelled twice, they could
/// drift, and the fixture would price a listing nobody asked for.
enum Shape<'a> {
    /// A Claude Code glob, with the one argument that family's pinned row
    /// names.
    Glob { pattern: &'a str },
    /// A glob carrying a second argument no committed artifact pins.
    ScopedGlob { pattern: &'a str, path: &'a str },
    /// A `find <dir> -name <pattern>` listing on a shell-shaped family,
    /// spelled as the published grammar spells it and scoped by an absolute
    /// directory so no working directory is in question.
    Find {
        family: &'static str,
        root: &'a Path,
        dir: &'a str,
        pattern: &'a str,
    },
    /// The same listing on the family that spells it with named arguments of
    /// its own.
    FindByName {
        root: &'a Path,
        dir: &'a str,
        pattern: &'a str,
    },
}

/// Whether Rift answers a scripted shape — which, in this script, is also
/// whether the bar's denominator counts it: the two searches Rift leaves
/// exactly as written are the two published beside the bar.
#[derive(Clone, Copy, PartialEq, Eq)]
enum Answered {
    Yes,
    No,
}

impl Shape<'_> {
    /// Whose hook the call is made on.
    fn family(&self) -> &'static str {
        match self {
            Self::Find { family, .. } => family,
            Self::FindByName { .. } => "antigravity",
            Self::Glob { .. } | Self::ScopedGlob { .. } => "claude-code",
        }
    }

    /// Which of the two shapes the answer arm recognises this is.
    fn lever(&self) -> &'static str {
        match self {
            Self::Glob { .. } | Self::ScopedGlob { .. } => "glob answer",
            Self::Find { .. } | Self::FindByName { .. } => "listing answer",
        }
    }

    /// The call itself, as the family's own pinned row spells it.
    fn payload(&self) -> String {
        match self {
            Self::Glob { pattern } => glob(pattern),
            Self::ScopedGlob { pattern, path } => serde_json::json!({
                "tool_name": "Glob",
                "tool_input": { "pattern": pattern, "path": path },
            })
            .to_string(),
            Self::Find {
                root, dir, pattern, ..
            } => {
                let at = root.join(dir);
                serde_json::json!({
                    "tool_name": "Bash",
                    "tool_input": { "command": format!("find {} -name '{pattern}'", common::shell_spelling(&at)) },
                    "cwd": root.display().to_string(),
                })
                .to_string()
            }
            Self::FindByName { root, dir, pattern } => serde_json::json!({
                "toolCall": {
                    "name": "find_by_name",
                    "args": {
                        "SearchDirectory": root.join(dir).display().to_string(),
                        "Pattern": pattern,
                    },
                },
            })
            .to_string(),
        }
    }

    /// The paths of the corpus this call matches, as the index will match them.
    fn matched(&self, files: &[GenFile]) -> Vec<String> {
        match self {
            Self::Glob { pattern } | Self::ScopedGlob { pattern, .. } => {
                matching_glob(files, pattern)
            }
            Self::Find { dir, pattern, .. } | Self::FindByName { dir, pattern, .. } => {
                matching_listing(files, dir, pattern)
            }
        }
    }
}

impl NameCase {
    /// A search of the kind Rift answers, which is one the bar is taken over.
    fn answered(label: &'static str, shape: &Shape<'_>, files: &[GenFile]) -> Self {
        Self::scripted(label, shape, files, Answered::Yes)
    }

    /// A search Rift leaves exactly as written, published beside the bar.
    fn left_alone(label: &'static str, shape: &Shape<'_>, files: &[GenFile]) -> Self {
        Self::scripted(label, shape, files, Answered::No)
    }

    /// One line of the script, with everything else worked out from the corpus
    /// rather than restated beside it.
    fn scripted(
        label: &'static str,
        shape: &Shape<'_>,
        files: &[GenFile],
        answered: Answered,
    ) -> Self {
        let matched = shape.matched(files);
        let priced = servable(&matched);
        let exact = hundred_is_knowable(&priced);
        Self {
            label,
            family: shape.family(),
            lever: shape.lever(),
            payload: shape.payload(),
            matched,
            priced,
            exact,
            answerable: answered == Answered::Yes,
            prescribed: answered == Answered::Yes,
        }
    }
}

/// The paths of the corpus one glob matches, as the index will match them.
fn matching_glob(files: &[GenFile], pattern: &str) -> Vec<String> {
    indexable(files)
        .into_iter()
        .filter(|path| rift_config::glob_match(pattern, path))
        .collect()
}

/// The paths of the corpus one `find <dir> -name <pattern>` listing matches:
/// the whole subtree, matched on the last segment.
fn matching_listing(files: &[GenFile], dir: &str, pattern: &str) -> Vec<String> {
    indexable(files)
        .into_iter()
        .filter(|path| {
            path.strip_prefix(dir)
                .and_then(|rest| rest.strip_prefix('/'))
                .is_some_and(|rest| {
                    rift_config::glob_match(pattern, rest.rsplit('/').next().unwrap_or(rest))
                })
        })
        .collect()
}

/// What is left of a match set once this repository's deny list has had it.
fn servable(paths: &[String]) -> Vec<String> {
    paths
        .iter()
        .filter(|path| !rift_config::glob_match(DENIED_GLOB, path))
        .cloned()
        .collect()
}

/// The whole script: seven name searches the bar is taken over, and two run in
/// the same session and published beside them.
fn name_cases(root: &Path, files: &[GenFile]) -> Vec<NameCase> {
    let mut cases = searches_the_bar_is_taken_over(root, files);
    cases.extend(searches_published_beside_the_bar(files));
    cases
}

