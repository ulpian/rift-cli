//! What a session over the document corpus costs with and without the
//! substitution — the nine-tenths bar for documents, and the figures the
//! asking channel publishes beside it.
//!
//! **What is priced here, and what is deliberately not.** Every document the
//! tree can price enters a pool: the declared native cost of the container a
//! client would have opened. The PDFs do not — a page's honest cost is a
//! vision-token rate no artifact in this tree pins — so they are read,
//! converted and published with what they cost, and divided by nothing.
//!
//! The corpus every figure below is taken over is generated by
//! `common/document_fixture.rs`, which is also where the claim that each of
//! its writers makes a readable document is proved (`document_corpus_e2e`);
//! one amendment followed to what the client really ran is
//! `document_substitution_e2e`.
//!
//! Every claim here is about the document seam, and the binary carries that
//! seam behind the `doc` feature: a build without it converts nothing, so
//! there is no substitution to price. The suite is the feature's, and says so
//! rather than failing a build that never promised one.
#![cfg(feature = "doc")]
#![allow(
    clippy::unwrap_used,
    clippy::expect_used,
    clippy::indexing_slicing,
    clippy::panic
)]

use std::path::Path;

mod common;

